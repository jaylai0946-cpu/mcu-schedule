/** 這筆學校行事曆事件涵蓋到、而且標題對得上的表。 */
export function orientationDaysFor(event: {
  title: string
  start: string
  end?: string
}): OrientationDay[] {
  const last = event.end ?? event.start
  return ORIENTATION_DAYS.filter(
    (day) =>
      day.date >= event.start &&
      day.date <= last &&
      day.match.some((keyword) => event.title.includes(keyword)),
  )
}
